  var STORAGE_KEY = 'site-lang';

  function getSavedLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'zh' || saved === 'en') return saved;
    } catch (e) {}
    return 'zh';
  }

  function saveLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  function applyLanguage(lang) {
    var dict = STRINGS[lang] || STRINGS.zh;

    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';

    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      if (Object.prototype.hasOwnProperty.call(dict, key)) {
        nodes[i].innerHTML = dict[key];
      }
    }

    var attrNodes = document.querySelectorAll('[data-i18n-attr]');
    for (var j = 0; j < attrNodes.length; j++) {
      var spec = attrNodes[j].getAttribute('data-i18n-attr').split(':');
      var attrName = spec[0];
      var attrKey = spec.slice(1).join(':');
      if (Object.prototype.hasOwnProperty.call(dict, attrKey)) {
        attrNodes[j].setAttribute(attrName, dict[attrKey]);
      }
    }

    var buttons = document.querySelectorAll('[data-lang-btn]');
    for (var k = 0; k < buttons.length; k++) {
      buttons[k].classList.toggle('is-active', buttons[k].getAttribute('data-lang-btn') === lang);
    }

    // 首次加载时，main.js 的 DOMContentLoaded 逻辑还没跑，交给它用这里刚设置好的
    // data-typewriter 值去打字即可；只有语言切换按钮被点击、页面已经跑过一次打字机
    // 效果之后，才需要在这里用新语言的文案重新打一遍。
    var tw = document.querySelector('[data-typewriter]');
    if (tw && tw.dataset.typewriterStarted) {
      var full = tw.getAttribute('data-typewriter');
      tw.textContent = '';
      var idx = 0;
      var type = function () {
        if (idx <= full.length) {
          tw.textContent = full.slice(0, idx);
          idx += 1;
          setTimeout(type, 28);
        }
      };
      type();
    }
  }

  document.addEventListener('click', function (e) {
    var btn = e.target.closest && e.target.closest('[data-lang-btn]');
    if (!btn) return;
    var lang = btn.getAttribute('data-lang-btn');
    saveLang(lang);
    applyLanguage(lang);
  });

  applyLanguage(getSavedLang());
